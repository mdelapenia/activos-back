import { after, before, test } from 'node:test';
import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { randomBytes } from 'node:crypto';
import { MongoClient } from 'mongodb';
import { MongoMemoryServer } from 'mongodb-memory-server';
import { generate } from 'otplib';
import { createHandler } from '../server/handler.mjs';
import { ensureIndexes } from '../server/database.mjs';
import { notifyNewLogin } from '../server/security-notices.mjs';
import { digest } from '../server/security.mjs';

const origin = 'https://activos.example.test';
const password = 'una contraseña segura de prueba';
const pin = '482915';
let mongo, client, db, server, base, now = Date.now();
before(async () => {
    mongo = await MongoMemoryServer.create();
    client = await new MongoClient(mongo.getUri()).connect();
    db = client.db('mfa_tests');
    await ensureIndexes(db);
    const env = { APP_ORIGIN: origin, NODE_ENV: 'production', MFA_ENCRYPTION_KEY: randomBytes(32).toString('base64') };
    server = createServer(createHandler({ database: async () => db, env, clock: () => now }));
    await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
    base = `http://127.0.0.1:${server.address().port}`;
});
after(async () => { if (server) await new Promise(resolve => server.close(resolve)); await client?.close(); await mongo?.stop(); });
async function call(path, { method = 'GET', body, cookie } = {}) {
    const response = await fetch(`${base}/api/${path}`, { method, headers: { Origin: origin, 'Content-Type': 'application/json', 'X-Activos-Request': '1', ...(cookie ? { Cookie: cookie } : {}) }, body: body === undefined ? undefined : JSON.stringify(body) });
    return { status: response.status, body: await response.json(), cookie: response.headers.get('set-cookie')?.split(';')[0] };
}

test('MFA protege ingreso, guarda secreto cifrado y consume códigos una sola vez', async () => {
    const email = 'mfa@example.test';
    const created = await call('register', { method: 'POST', body: { name: 'Prueba', email, password, confirmPassword: password, pin, confirmPin: pin } });
    assert.equal(created.status, 201);
    assert.equal((await call('mfa/setup', { method: 'POST', body: { pin } })).status, 401);
    const setup = await call('mfa/setup', { method: 'POST', cookie: created.cookie, body: { pin } });
    assert.equal(setup.status, 200);
    const token = await generate({ secret: setup.body.secret, epoch: Math.floor(now / 1000) });
    const active = await call('mfa/confirm', { method: 'POST', cookie: created.cookie, body: { pin, code: token } });
    assert.equal(active.status, 200);
    assert.equal(setup.body.codes.length, 8);
    const user = await db.collection('users').findOne({ email });
    const stored = await db.collection('mfa').findOne({ _id: user._id });
    assert.ok(!JSON.stringify(stored).includes(setup.body.secret));
    assert.ok(!JSON.stringify(stored).includes(setup.body.codes[0]));
    const login = mfaCode => call('login', { method: 'POST', body: { email, password, mfaCode, device: { platform: 'ios', name: 'Prueba' } } });
    const required = await login();
    assert.equal(required.body.code, 'MFA_REQUIRED');
    assert.equal(required.cookie, undefined);
    assert.equal((await login(token)).body.code, 'MFA_INVALID');
    const status = await call('mfa', { cookie: created.cookie });
    assert.equal(status.body.recoveryCount, 8);
    assert.equal(status.body.recoveryViewAvailable, true);
    assert.ok(!JSON.stringify(status.body).includes(setup.body.secret));
    assert.equal((await call('mfa/details', { method: 'POST', body: { code: token } })).status, 401);
    assert.equal((await call('mfa/details', { method: 'POST', cookie: created.cookie, body: { code: setup.body.codes[1] } })).status, 401);
    now += 31_000;
    const revealToken = await generate({ secret: setup.body.secret, epoch: Math.floor(now / 1000) });
    const revealed = await call('mfa/details', { method: 'POST', cookie: created.cookie, body: { code: revealToken } });
    assert.equal(revealed.status, 200);
    assert.equal(revealed.body.secret, setup.body.secret);
    assert.deepEqual(revealed.body.codes, setup.body.codes);
    assert.equal((await call('mfa/details', { method: 'POST', cookie: created.cookie, body: { code: revealToken } })).status, 401);
    now += 31_000;
    const next = await generate({ secret: setup.body.secret, epoch: Math.floor(now / 1000) });
    const logged = await login(next);
    assert.equal(logged.status, 200);
    assert.ok(logged.body.deviceToken);
    assert.equal((await login(next)).body.code, 'MFA_INVALID');
    assert.equal((await login(setup.body.codes[0])).status, 200);
    assert.equal((await login(setup.body.codes[0])).body.code, 'MFA_INVALID');
    now += 31_000;
    const afterUse = await generate({ secret: setup.body.secret, epoch: Math.floor(now / 1000) });
    const remaining = await call('mfa/details', { method: 'POST', cookie: created.cookie, body: { code: afterUse } });
    assert.deepEqual(remaining.body.codes, setup.body.codes.slice(1));
    // Las cuentas anteriores solo tienen hashes; migrarlas requiere generar otros códigos.
    await db.collection('mfa').updateOne({ _id: user._id }, { $unset: { recoveryEntries: '' } });
    assert.equal((await call('mfa', { cookie: created.cookie })).body.recoveryViewAvailable, false);
    now += 31_000;
    const legacyToken = await generate({ secret: setup.body.secret, epoch: Math.floor(now / 1000) });
    const legacy = await call('mfa/details', { method: 'POST', cookie: created.cookie, body: { code: legacyToken } });
    assert.equal(legacy.body.secret, setup.body.secret);
    assert.equal(legacy.body.codes, null);
    assert.equal((await call('mfa/recovery/regenerate', { method: 'POST', cookie: created.cookie, body: { code: legacyToken } })).status, 401);
    now += 31_000;
    const regenerationToken = await generate({ secret: setup.body.secret, epoch: Math.floor(now / 1000) });
    const regenerated = await call('mfa/recovery/regenerate', { method: 'POST', cookie: created.cookie, body: { code: regenerationToken } });
    assert.equal(regenerated.status, 200);
    assert.equal(regenerated.body.codes.length, 8);
    assert.equal((await login(setup.body.codes[1])).body.code, 'MFA_INVALID');
    assert.equal((await call('mfa', { method: 'DELETE', cookie: created.cookie, body: { pin, code: regenerated.body.codes[0] } })).status, 200);
    assert.equal((await login()).status, 200);

    // Una cuenta con MFA activo también puede desactivarlo con PIN y contraseña.
    const setupAgain = await call('mfa/setup', { method: 'POST', cookie: created.cookie, body: { pin } });
    assert.equal(setupAgain.status, 200);
    const fresh = await generate({ secret: setupAgain.body.secret, epoch: Math.floor(now / 1000) });
    assert.equal((await call('mfa/confirm', { method: 'POST', cookie: created.cookie, body: { pin, code: fresh } })).status, 200);
    const disable = body => call('mfa', { method: 'DELETE', cookie: created.cookie, body });
    assert.equal((await disable({ pin, password: 'contraseña incorrecta' })).status, 401);
    assert.equal((await disable({ pin: '000111', password })).status, 401);
    assert.equal((await disable({ password })).status, 400);
    assert.equal((await call('mfa', { cookie: created.cookie })).body.enabled, true);
    assert.equal((await disable({ pin, password })).status, 200);
    assert.equal((await call('mfa', { cookie: created.cookie })).body.enabled, false);
    assert.equal((await login()).status, 200);
});

test('avisa solo a la cuenta del ingreso nuevo y reconoce navegador y dispositivo', async () => {
    const user = { _id: 'avisos-test' };
    const other = { _id: 'otra-cuenta' };
    await db.collection('push_subscriptions').insertMany([{ _id: 'push-a', userId: user._id }, { _id: 'push-b', userId: other._id }]);
    await db.collection('telegram_subscriptions').insertOne({ _id: user._id, userId: user._id, chatId: '123' });
    const sent = [];
    const deliver = async (_db, row, payload) => { sent.push({ id: row._id, payload }); return true; };
    const env = { TELEGRAM_BOT_TOKEN: 'test' };
    const browserId = 'a'.repeat(64);
    await notifyNewLogin(db, user, { browserId }, env, now, deliver);
    assert.equal(sent.length, 2);
    assert.ok(sent.some(row => row.id === 'push-a'));
    assert.ok(sent.every(row => row.id !== 'push-b'));
    assert.match(sent[0].payload.body, /navegador/);
    await notifyNewLogin(db, user, { browserId }, env, now, deliver);
    assert.equal(sent.length, 2);
    const token = 'z'.repeat(43);
    await db.collection('devices').insertOne({ _id: digest(token), userId: user._id, publicId: 'test-device' });
    await notifyNewLogin(db, user, { device: { platform: 'ios' }, previousDeviceToken: token }, env, now, deliver);
    assert.equal(sent.length, 2);
    await notifyNewLogin(db, user, { device: { platform: 'ios' } }, env, now, deliver);
    assert.equal(sent.length, 4);
});
